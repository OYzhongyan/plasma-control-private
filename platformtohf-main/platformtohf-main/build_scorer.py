from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parents[1] / "evaluation/eval/score"
ORDER = ["config", "metrics", "penalties", "scoring", "tasks", "evaluate_core", "__init__"]


